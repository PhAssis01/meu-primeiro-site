// Precio con el formato del idioma activo (alquiler: «/mes»).
export function formatPrice(property, t) {
  const amount = new Intl.NumberFormat(t.locale, {
    style: 'currency',
    currency: 'EUR',
    maximumFractionDigits: 0,
  }).format(property.price)
  return property.operation === 'alquiler' ? `${amount}${t.perMonth}` : amount
}

export function formatAmount(value, t) {
  return new Intl.NumberFormat(t.locale, { style: 'currency', currency: 'EUR', maximumFractionDigits: 0 }).format(value)
}
